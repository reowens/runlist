test('OpenCode reports an older generated version even when its JavaScript matches', t => {
  const home = mkdtempSync(path.join(os.tmpdir(), 'runlist-host-version-'));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const root = path.join(home, 'candidate'), directory = path.join(home, '.config', 'opencode', 'plugin');
  mkdirSync(path.join(root, 'assets', 'opencode'), { recursive: true }); mkdirSync(directory, { recursive: true });
  writeFileSync(path.join(root, 'package.json'), JSON.stringify({ name: 'runlist', version: '1.2.3' }));
  const body = '// same JavaScript\n';
  writeFileSync(path.join(root, 'assets', 'opencode', 'plugin.js'), body);
  writeFileSync(path.join(directory, 'runlist.js'), '// runlist-generated:1.2.2\n// Generated by `runlist install opencode`. Refreshed by `runlist update`.\n// Hand edits are overwritten — remove with `runlist install opencode --remove`.\n\n' + body);
  const report = agentHostReport({}, { root, home, env: { PATH: '' } });
  assert.equal(report.hosts.opencode.files[0].version, '1.2.2');
  assert.equal(report.hosts.opencode.expectedVersion, '1.2.3');
  assert.equal(report.hosts.opencode.state, 'stale');
});

function fixture(t) {
  const home = realpathSync(mkdtempSync(path.join(os.tmpdir(), 'runlist-hosts-')));
  t.after(() => rmSync(home, { recursive: true, force: true }));
  const write = (file, content) => { mkdirSync(path.dirname(file), { recursive: true }); writeFileSync(file, content); return file; };
  const json = (file, data) => write(file, JSON.stringify(data));
  const root = path.join(home, 'candidate');
  json(path.join(root, 'package.json'), { name: 'runlist', version: '1.2.3' });
  const plugin = (dir, body = 'current') => {
    json(path.join(dir, '.claude-plugin/plugin.json'), { name: 'runlist', version: '1.2.3' });
    write(path.join(dir, 'skills/runlist/SKILL.md'), body);
    json(path.join(dir, 'hooks.json'), { hooks: { SessionStart: body } });
    write(path.join(dir, 'hooks/start.sh'), '#!/bin/sh\n');
  };
  plugin(path.join(root, 'plugins/runlist'));
  json(path.join(root, 'plugins/runlist-codex/.codex-plugin/plugin.json'), { name: 'runlist-codex', version: '1.2.3' });
  write(path.join(root, 'plugins/runlist-codex/skills/runlist/SKILL.md'), 'codex workflow');
  write(path.join(root, 'plugins/runlist-codex/hooks.json'), '{"hooks":{}}');
  write(path.join(root, 'assets/opencode/plugin.js'), '// fixture asset\nexport const Integration = () => {};\n');
  const binary = (file, native = false) => { write(file, native ? Buffer.from('7f454c4600000000', 'hex') : `#!/bin/sh\ntouch '${path.join(home, 'MUST_NOT_EXECUTE')}'\n`); chmodSync(file, 0o755); return file; };
  const options = { root, home, env: { PATH: '' } };
  const registry = (dir, plugins) => json(path.join(dir, 'plugins/installed_plugins.json'), { version: 2, plugins });
  const catalog = (dir, pluginSource = './plugins/runlist', source = { source: 'github', repo: 'reowens/runlist' }) => {
    const location = path.join(home, 'marketplace');
    json(path.join(dir, 'plugins/known_marketplaces.json'), { runlist: { source, installLocation: location } });
    json(path.join(location, '.claude-plugin/marketplace.json'), { name: 'runlist', plugins: [{ name: 'runlist', source: pluginSource }] });
    plugin(path.join(location, 'plugins/runlist'), 'published');
    return location;
  };
  return { home, root, write, json, binary, plugin, options, registry, catalog, report: extra => agentHostReport({}, { ...options, ...extra }) };
}

test('discovers only bounded home profiles, environment and absolute selectors; deduplicates physical stores', t => {
  const f = fixture(t), defaultDir = path.join(f.home, '.claude'), robot = path.join(f.home, '.claude-robot');
  f.registry(defaultDir, { 'runlist@runlist': [{ scope: 'user', version: '1.2.3' }], 'dotmd@dotmd': { scope: 'user', version: '0.1.0' } });
  mkdirSync(robot);
  symlinkSync(path.join(defaultDir, 'plugins'), path.join(robot, 'plugins'), 'dir');
  f.json(path.join(defaultDir, 'settings.json'), { enabledPlugins: { 'runlist@runlist': true }, env: { TOKEN: 'CREDENTIAL_MUST_NOT_APPEAR' }, systemPrompt: 'PROMPT_MUST_NOT_APPEAR' });
  f.json(path.join(robot, 'settings.json'), { enabledPlugins: { 'runlist@runlist': false } });
  const active = path.join(f.home, 'active-profile'), selected = path.join(f.home, 'selected profile');
  f.registry(path.join(f.home, 'unrelated/nested/.claude-hidden'), {});
  const profiles = discoverClaudeProfiles({ home: f.home, env: { CLAUDE_CONFIG_DIR: active }, configDirs: [selected] });
  assert.equal(profiles.length, 3);
  assert.equal(profiles[0].storeKey, realpathSync(path.join(defaultDir, 'plugins')));
  assert.deepEqual(profiles[0].configDirs, [defaultDir, robot]);
  assert.equal(profiles[0].plugins.length, 2);
  assert.equal(profiles[0].installed.id, 'runlist@runlist');
  assert.deepEqual(profiles[0].settings.map(s => s.enabledPlugins['runlist@runlist']), [true, false]);
  assert.equal(profiles[1].configDir, active);
  assert.equal(profiles[2].source, 'explicit');
  assert.equal(profiles[2].registryState, 'missing');
  assert.equal(JSON.stringify(profiles).includes('MUST_NOT_APPEAR'), false);
  assert.equal(profiles.some(p => p.configDir.includes('hidden')), false);
  const selectedAlias = discoverClaudeProfiles({ home: f.home, env: {}, configDirs: [robot] })[0];
  assert.equal(selectedAlias.configDir, robot);
  assert.equal(selectedAlias.source, 'explicit');
  assert.equal(selectedAlias.storeKey, profiles[0].storeKey);
  const activeAlias = discoverClaudeProfiles({ home: f.home, env: { CLAUDE_CONFIG_DIR: robot } })[0];
  assert.equal(activeAlias.configDir, robot);
  assert.equal(activeAlias.source, 'environment');
  assert.throws(() => discoverClaudeProfiles({ home: f.home, env: {}, configDirs: ['relative'] }), /absolute/);
});

