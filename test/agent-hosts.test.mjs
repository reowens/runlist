test('Codex keeps home marketplace source distinct from active CODEX_HOME cached and installed state', t => {
  const f = fixture(t), source = path.join(f.home, 'plugins/runlist-codex'), active = path.join(f.home, 'codex-profile');
  cpSync(path.join(f.root, 'plugins/runlist-codex'), source, { recursive: true });
  f.json(path.join(source, '.runlist-generated.json'), { version: '1.2.3' });
  f.json(path.join(f.home, '.agents/plugins/marketplace.json'), { name: 'personal', plugins: [{ name: 'runlist-codex', source: { source: 'local', path: './plugins/runlist-codex' } }] });
  const cache = path.join(active, 'plugins/cache/personal/runlist-codex/1.2.3'); cpSync(source, cache, { recursive: true });
  f.write(path.join(cache, 'hooks.json'), '{"hooks":{"changed":true}}');
  let codex = f.report({ env: { PATH: '', CODEX_HOME: active } }).hosts.codex;
  assert.equal(codex.source.path, source); assert.equal(codex.source.state, 'current');
  assert.equal(codex.configDir, active); assert.equal(codex.cached.length, 1);
  assert.equal(codex.cached[0].sameSource, false);
  assert.equal(codex.installed.state, 'unknown'); assert.equal(codex.loaded, 'unknown');
  f.write(path.join(source, 'hooks.json'), 'drift');
  codex = f.report().hosts.codex; assert.equal(codex.source.state, 'stale');
  rmSync(path.join(source, '.runlist-generated.json'));
  codex = f.report().hosts.codex; assert.equal(codex.source.state, 'foreign'); assert.equal(codex.repair.targetable, false);
});

test('OpenCode reports exact generated asset parity and preserves foreign files in both directory spellings', t => {
  const f = fixture(t), config = path.join(f.home, 'opencode-profile'), file = path.join(config, 'plugin/runlist.js');
  const asset = readFileSync(path.join(f.root, 'assets/opencode/plugin.js'), 'utf8');
  const generated = ['// runlist-generated:1.2.3', '// Generated by `runlist install opencode`. Refreshed by `runlist update`.',
    '// Hand edits are overwritten — remove with `runlist install opencode --remove`.', ''].join('\n') + asset;
  f.write(file, generated);
  const options = { env: { PATH: '', OPENCODE_CONFIG_DIR: config } };
  let opencode = f.report(options).hosts.opencode;
  assert.equal(opencode.files[0].sameSource, true); assert.equal(opencode.state, 'current'); assert.equal(opencode.loaded, 'unknown');
  f.write(file, generated + '\n// drift'); assert.equal(f.report(options).hosts.opencode.state, 'stale');
  const foreign = path.join(config, 'plugins/dotmd.js'); f.write(foreign, 'unmarked user content');
  opencode = f.report(options).hosts.opencode; assert.equal(opencode.state, 'foreign'); assert.equal(opencode.files.length, 2);
  assert.equal(opencode.repair.targetable, false); assert.equal(readFileSync(foreign, 'utf8'), 'unmarked user content');
});

test('report and human formatter are read-only, secret-free and show executable, profile, source and loading uncertainty', t => {
  const f = fixture(t), dir = path.join(f.home, '.claude');
  f.json(path.join(dir, 'settings.json'), { enabledPlugins: { 'runlist@runlist': false }, env: { TOKEN: 'PRIVATE_TOKEN' }, prompt: 'PRIVATE_PROMPT' });
  f.binary(path.join(f.home, 'bin/claude'));
  const before = readdirSync(dir);
  const report = f.report({ env: { PATH: path.join(f.home, 'bin') } }), formatted = formatAgentHostReport(report);
  assert.deepEqual(readdirSync(dir), before);
  assert.equal(existsSync(path.join(f.home, 'MUST_NOT_EXECUTE')), false);
  assert.equal(report.readOnly, true); assert.equal(report.schemaVersion, 1);
  assert.match(formatted, /Selected executable: .*claude \(wrapper\)/);
  assert.match(formatted, /Enabled settings: .*runlist@runlist=false/);
  assert.match(formatted, /registry missing/); assert.match(formatted, /loaded unknown/);
  assert.match(formatted, /Personal marketplace:/); assert.match(formatted, /Active Codex profile:/);
  assert.equal((JSON.stringify(report) + formatted).includes('PRIVATE_'), false);
});
